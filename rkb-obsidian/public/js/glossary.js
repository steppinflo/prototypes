const tip = (title, body) => `<b>${escapeHtml(title)}</b><div style="margin-top:3px">${escapeHtml(body)}</div>`;
function escapeHtml(s) {
  return String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
}

/** Explanation for a column header, or null when there is none. */
export function columnHelp(label, ctx) {
  const text = (ctx && C[`${ctx}.${label}`]) ?? C[label];
  return text ? tip(label, text) : null;
}

export function kpiHelp(label) {
  const text = KPI[label];
  return text ? tip(label, text) : null;
}

export function termHelp(term) {
  if (!TERMS[term]) return null;
  const body = TERMS[term].replace(/^[^—]+— /, '');
  return tip(term, body[0].toUpperCase() + body.slice(1));
}

